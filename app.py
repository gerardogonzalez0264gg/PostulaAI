# Crear tablas y actualizar columnas sin borrar información existente.
with app.app_context():
    db.create_all()

    columns = {
        row[1]
        for row in db.session.execute(
            text("PRAGMA table_info(offer)")
        ).fetchall()
    }

    migrations = {
        "analysis": "TEXT DEFAULT ''",
        "form_questions": "TEXT DEFAULT ''",
        "form_answers": "TEXT DEFAULT ''",
        "ya_revise": "BOOLEAN NOT NULL DEFAULT 0",
        "ya_postule": "BOOLEAN NOT NULL DEFAULT 0"
    }

    for column, definition in migrations.items():
        if column not in columns:
            db.session.execute(
                text(f"ALTER TABLE offer ADD COLUMN {column} {definition}")
        )

    inbox_columns = {
        row[1]
        for row in db.session.execute(
            text("PRAGMA table_info(inbox_item)")
        ).fetchall()
    }

    if "gmail_id" not in inbox_columns:
        db.session.execute(
            text("ALTER TABLE inbox_item ADD COLUMN gmail_id VARCHAR(120)")
        )

    db.session.execute(
        text("""
            CREATE UNIQUE INDEX IF NOT EXISTS
            ix_inbox_item_gmail_id
            ON inbox_item (gmail_id)
        """)
    )

    db.session.commit()

    if not Profile.query.first():
        db.session.add(Profile())
        db.session.commit()


def parse_offer_analysis(analysis):
    """Convert the saved AI analysis into structured data."""

    if not analysis:
        return None, ""

    try:
        data = json.loads(analysis)

        if isinstance(data, dict):
            return data, ""

    except (ValueError, TypeError):
        pass

    # Compatibility with analyses generated by older versions.
    return None, analysis


def parse_form_answers(answers_text):
    """Read previously saved form answers."""

    if not answers_text:
        return []

    try:
        data = json.loads(answers_text)

        if isinstance(data, list):
            return data

    except (ValueError, TypeError):
        pass

    return []


