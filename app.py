@app.route("/offers/search", methods=["POST"])
def search_offers():
    role = request.form.get("role", "").strip()
    location = request.form.get("location", "").strip()
    commune = request.form.get("commune", "").strip()
    work_mode = request.form.get("work_mode", "").strip()

    try:
        results = search_jobs(
            role,
            location,
            commune,
            work_mode
        )

        saved_results = []

        for item in results:
            saved = JobSearchResult.query.filter_by(
                url=item["url"]
            ).first()

            if saved:
                saved.title = item["title"]
                saved.source = item["source"]
                saved.description = item["description"]
                saved.result_type = item["result_type"]
                saved.is_general = item["is_general"]
            else:
                saved = JobSearchResult(
                    title=item["title"],
                    url=item["url"],
                    source=item["source"],
                    description=item["description"],
                    result_type=item["result_type"],
                    is_general=item["is_general"]
                )
                db.session.add(saved)

            saved_results.append(saved)

        db.session.commit()

        return render_template(
            "offers.html",
            offers=Offer.query.order_by(
                Offer.created_at.desc()
            ).all(),
            search_results=saved_results,
            applied_offers=Offer.query.filter_by(
                ya_postule=True
            ).order_by(Offer.created_at.desc()).all(),
            applied_search_results=JobSearchResult.query.filter_by(
                ya_postule=True
            ).order_by(JobSearchResult.created_at.desc()).all(),
            search_error=None,
            mode="search"
        )

    except JobSearchError as exc:
        return render_template(
            "offers.html",
            offers=Offer.query.order_by(
                Offer.created_at.desc()
            ).all(),
            search_results=[],
            applied_offers=Offer.query.filter_by(
                ya_postule=True
            ).order_by(Offer.created_at.desc()).all(),
            applied_search_results=JobSearchResult.query.filter_by(
                ya_postule=True
            ).order_by(JobSearchResult.created_at.desc()).all(),
            search_error=str(exc),
            mode="search"
        )


