@app.route("/offers", methods=["GET", "POST"])
def offers():
    if request.method == "POST":
        url = request.form.get("url", "").strip()

        if not url:
            flash("Pega el enlace de la oferta laboral.", "warning")
            return redirect(url_for("offers", mode="analyze"))

        try:
            offer_text = extract_offer_text(url)
            extraction = extract_offer_details(offer_text)

            if not extraction.get("success"):
                flash(
                    "No se pudieron identificar los datos de la oferta: "
                    + extraction.get("error", "Error desconocido"),
                    "warning"
                )
                return redirect(url_for("offers", mode="analyze"))

            details = extraction["details"]

            if not details.get("title"):
                flash("No pudimos identificar el cargo en la publicación.", "warning")
                return redirect(url_for("offers", mode="analyze"))

            description = details.get("description") or offer_text

            offer = Offer(
                title=details["title"],
                company=details.get("company", ""),
                source="Enlace web",
                url=url,
                description=description,
                location=details.get("location", ""),
                work_mode=details.get("work_mode", "No especificado")
            )

            db.session.add(offer)
            db.session.commit()

            result = generate_offer_analysis(
                Profile.query.first(),
                description
            )

            if result.get("success"):
                offer.analysis = result["analysis"]
                db.session.commit()
                flash("Oferta extraída, guardada y analizada correctamente.", "success")
            else:
                flash(
                    "La oferta se guardó, pero no se pudo generar el análisis: "
                    + result.get("analysis", "Error desconocido"),
                    "warning"
                )

            return redirect(url_for("offer_detail", offer_id=offer.id))

        except OfferFetchError as exc:
            flash(str(exc), "warning")
            return redirect(url_for("offers", mode="analyze"))

        except Exception as exc:
            db.session.rollback()
            flash("Ocurrió un error al procesar la oferta: " + str(exc), "danger")
            return redirect(url_for("offers", mode="analyze"))

    mode = request.args.get("mode", "search")

    return render_template(
        "offers.html",
        offers=Offer.query.order_by(Offer.created_at.desc()).all(),
        search_results=[],
        applied_offers=Offer.query.filter_by(
            ya_postule=True
        ).order_by(Offer.created_at.desc()).all(),
        applied_search_results=JobSearchResult.query.filter_by(
            ya_postule=True
        ).order_by(JobSearchResult.created_at.desc()).all(),
        search_error=None,
        analysis=None,
        mode=mode
    )


@app.route("/offers/generate-answer", methods=["POST"])
def generate_individual_answer():
    data = request.get_json(silent=True) or {}

    question = str(data.get("question") or "").strip()
    title = str(data.get("title") or "").strip()
    company = str(data.get("company") or "").strip()
    context = str(data.get("context") or "").strip()

    if not question:
        return jsonify({
            "success": False,
            "error": "Escribe una pregunta primero."
        }), 400

    offer_context = f"""
    Cargo: {title or 'No especificado'}
    Empresa: {company or 'No especificada'}

    CONTEXTO DE LA OFERTA:
    {context or 'No proporcionado'}
    """

    result = generate_form_answers(
        Profile.query.first(),
        offer_context,
        question
    )

    if not result.get("success"):
        return jsonify({
            "success": False,
            "error": result.get("error", "No se pudo generar la respuesta.")
        }), 500

    answers = result.get("answers", [])

    if not answers or not answers[0].get("answer"):
        return jsonify({
            "success": False,
            "error": "La IA no devolvió una respuesta válida."
        }), 500

    return jsonify({
        "success": True,
        "answer": answers[0]["answer"]
    })


