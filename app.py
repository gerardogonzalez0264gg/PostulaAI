@app.route("/gmail/connect")
def gmail_connect():
    try:
        code_verifier = secrets.token_urlsafe(64)

        flow = create_oauth_flow(
            code_verifier=code_verifier
        )

        authorization_url, state = flow.authorization_url(
            access_type="offline",
            include_granted_scopes="true",
            prompt="consent"
        )

        session["gmail_oauth_state"] = state
        session["gmail_code_verifier"] = code_verifier

        return redirect(authorization_url)

    except GmailServiceError as exc:
        flash(str(exc), "danger")
        return redirect(url_for("inbox"))

    except Exception as exc:
        flash(
            "No se pudo iniciar la conexión con Gmail: " + str(exc),
            "danger"
        )
        return redirect(url_for("inbox"))

@app.route("/gmail/callback")
def gmail_callback():
    state = session.pop("gmail_oauth_state", None)
    code_verifier = session.pop("gmail_code_verifier", None)

    if not state or not code_verifier:
        flash(
            "No se encontró la sesión de autorización. Intenta nuevamente.",
            "warning"
        )
        return redirect(url_for("inbox"))

    try:
        flow = create_oauth_flow(
            state=state,
            code_verifier=code_verifier
        )

        flow.fetch_token(
            authorization_response=request.url
        )

        save_credentials(flow.credentials)

        flash("¡Gmail conectado correctamente!", "success")

    except Exception as exc:
        flash(
            "No se pudo completar la autorización de Gmail: " + str(exc),
            "danger"
        )

    return redirect(url_for("inbox"))

@app.route("/gmail/sync", methods=["POST"])
def gmail_sync():
    try:
        emails = get_recent_emails(max_results=50)
        imported = 0

        for email in emails:
            existing = InboxItem.query.filter_by(
                gmail_id=email["gmail_id"]
            ).first()

            if existing:
                continue

            item = InboxItem(
                gmail_id=email["gmail_id"],
                provider="Gmail",
                sender=email["sender"],
                subject=email["subject"],
                body_preview=email["preview"],
                category=email["category"]
            )

            db.session.add(item)
            imported += 1

        db.session.commit()

        flash(
            f"Sincronización completada. Se importaron {imported} correos nuevos.",
            "success"
        )

    except GmailServiceError as exc:
        db.session.rollback()
        flash(str(exc), "warning")

    except Exception as exc:
        db.session.rollback()
        flash("Error al sincronizar Gmail: " + str(exc), "danger")

    return redirect(url_for("inbox"))


